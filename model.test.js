import test from 'node:test';
import assert from 'node:assert/strict';
import { emptyState, saveAnswer, countAnswers, nextQuestion, bookText, restoreState, saveProfile, timelineEntries, saveManuscript, sourceFingerprint, approvedChapters, manuscriptText, chapters, CHAPTER_TARGETS, BOOK_TARGET, textLength, materialStats, approvedCharacters, sanitizeOptionalPlan, fallbackOptionalPlan, bookSource, bookFingerprint, answerExportText, answerExportFilename, nextSupplementBatch, SUPPLEMENT_LIMIT } from './model.js';
test('answers advance chapters, updates do not inflate progress, and the book retains the author’s words', () => {
  let state = emptyState('さちこ');
  assert.equal(nextQuestion(state, 0), 0);
  state = saveAnswer(state, 0, 0, '  海の近くで育ちました。  ');
  assert.equal(nextQuestion(state, 0), 1);
  state = saveAnswer(state, 0, 0, '山の近くで育ちました。');
  assert.equal(countAnswers(state), 1);
  state = saveAnswer(state, 0, 1, '夕焼けが好きでした。');
  state = saveAnswer(state, 0, 2, '元気な子でした。');
  assert.equal(nextQuestion(state, 0), 3);
  assert.equal(countAnswers(state, 1), 0);
  assert.equal(countAnswers(state), 3);
  assert.match(bookText(state), /さちこの人生の物語/);
  assert.match(bookText(state), /第1章　はじまりの風景/);
  assert.match(bookText(state), /山の近くで育ちました。/);
  assert.doesNotMatch(bookText(state), /海の近く|第2章/);
});
test('the book exports reviewed prose, excludes raw answers and invalidates approval when sources change', () => {
  let state=saveAnswer(emptyState('母'),0,0,'尾道。兄と海へ。');
  state=saveManuscript(state,0,'幼い頃の私は、尾道で兄と海へ向かった。','ai');
  assert.equal(approvedChapters(state),0);
  assert.doesNotMatch(manuscriptText(state),/尾道。兄と海へ。|幼い頃の私は/);
  state.manuscripts[0].approved=true;
  assert.equal(approvedChapters(state),1);
  assert.match(manuscriptText(state),/幼い頃の私は/);
  assert.doesNotMatch(manuscriptText(state),/尾道。兄と海へ。/);
  assert.deepEqual(restoreState(JSON.stringify(state)),state);
  const before=sourceFingerprint(state,0);
  state=saveAnswer(state,0,0,'実際は姉と海へ行きました。');
  assert.notEqual(sourceFingerprint(state,0),before);
  assert.equal(approvedChapters(state),0);
  assert.doesNotMatch(manuscriptText(state),/兄と海へ向かった/);
});
test('basic information persists with answers, the timeline orders supplied years and does not invent dates', () => {
  assert.throws(() => saveProfile(emptyState(), { name: '  ' }));
  assert.throws(() => saveProfile(emptyState(), { name: '母', birthYear: '2100' }));
  let state = saveProfile(emptyState(), { name: '母', birthYear: '1960', birthplace: '尾道', childhoodFamily: '両親と兄' });
  state = saveAnswer(state, 0, 0, '山のそばで育ちました。');
  state = saveAnswer(state, 3, 0, '初めて就職した日。');
  state = saveAnswer(state, 2, 0, '学生時代のお話。');
  state.eventYears = { '3:0': '1980年ごろ', '2:0': '1975年ごろ' };
  assert.deepEqual(timelineEntries(state).map(e => e.year), ['1960', '1975年ごろ', '1980年ごろ', '']);
  assert.deepEqual(restoreState(JSON.stringify(state)), state);
  assert.match(bookText(state), /生まれた年：1960/);
  assert.match(bookText(state), /【1975年ごろ】/);
  const legacy = restoreState(JSON.stringify({name:'母',answers:{'0:0':'以前の回答'},started:true}));
  assert.equal(legacy.answers['0:0'], '以前の回答');
  assert.equal(legacy.profileComplete, false);
});
test('blank and unknown answers are rejected and persisted state recovers safely', () => {
  assert.throws(() => saveAnswer(emptyState(), 0, 0, '   '));
  assert.throws(() => saveAnswer(emptyState(), 6, 0, '回答'));
  assert.deepEqual(restoreState('not json'), emptyState());
  const original = saveAnswer(emptyState('母'), 4, 2, '自分らしく生きてね。');
  assert.deepEqual(restoreState(JSON.stringify(original)), original);
  const recovered = restoreState(JSON.stringify({name:'母',answers:{'4:2':'言葉','10:1':'unknown','0:0':false},started:true}));
  assert.deepEqual(recovered.answers, {'4:2':'言葉'});
});
test('5000-character plan preserves old questions and counts only approved prose, not notes or whitespace', () => {
  assert.equal(CHAPTER_TARGETS.reduce((n,x)=>n+x,0),BOOK_TARGET);
  assert.equal(chapters.reduce((n,c)=>n+c.questions.length,0),36);
  const legacy=restoreState(JSON.stringify({name:'母',answers:{'0:0':'尾道で育った。'},started:true}));
  assert.equal(legacy.answers['0:0'],'尾道で育った。');
  assert.match(chapters[0].questions[0],/どんな場所/);
  assert.equal(nextQuestion(legacy,0),1);
  legacy.followups['0:0']=[{question:'誰と？',answer:'兄と海へ行った。'}];
  assert.equal(materialStats(legacy,0).characters,textLength('尾道で育った。兄と海へ行った。'));
  let state=saveManuscript(legacy,0,'あ'.repeat(900)+'\n\n  ','ai');
  assert.equal(approvedCharacters(state),0);
  state.manuscripts[0].approved=true;
  assert.equal(approvedCharacters(state),900);
  assert.equal(textLength('あ い\nう'),3);
});
test('finite interview preserves skips, generated book and recoverable generation checkpoints on reload', () => {
  const state=emptyState('母');
  state.skipped={'0:0':true,'99:0':true};
  state.bookDraft={text:'本の本文',source:'source',approved:false};
  state.bookWork={source:'source',parts:{0:'完成した章'}};
  const restored=restoreState(JSON.stringify(state));
  assert.deepEqual(restored.skipped,{'0:0':true});
  assert.deepEqual(restored.bookDraft,state.bookDraft);
  assert.deepEqual(restored.bookWork,state.bookWork);
});
test('optional questions are capped at ten, survive reload, and their answers reach the book', () => {
  const plan=sanitizeOptionalPlan(Array.from({length:15},(_,i)=>({chapterIndex:0,question:`幼い頃の具体的な出来事${i}を教えてください。`})));
  assert.equal(plan.length,10);
  let state=saveAnswer(emptyState('母'),0,0,'尾道');
  const before=bookFingerprint(state);
  state.optionalInterview={questions:plan,answers:{0:'祖母と祭りへ行った。'},skipped:{1:true},done:false};
  const restored=restoreState(JSON.stringify(state));
  assert.deepEqual(restored.optionalInterview,state.optionalInterview);
  assert.equal(bookSource(restored).length,2);
  assert.equal(bookSource(restored)[1].answer,'祖母と祭りへ行った。');
  assert.notEqual(bookFingerprint(restored),before);
  assert.equal(sanitizeOptionalPlan([{chapterIndex:0,question:chapters[0].questions[0]},{chapterIndex:0,question:'  新しい質問？ '},{chapterIndex:0,question:'新しい質問?'},{chapterIndex:99,question:'不明'}]).length,1);
});
test('fallback optional questions only cover sparse answered chapters and can be unnecessary', () => {
  const state=saveAnswer(emptyState('母'),0,0,'尾道');
  const plan=fallbackOptionalPlan(state);
  assert.ok(plan.length>0&&plan.length<=10);
  assert.ok(plan.every(q=>q.chapterIndex===0));
  assert.deepEqual(fallbackOptionalPlan(emptyState()),[]);
});
